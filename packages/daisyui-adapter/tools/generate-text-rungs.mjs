// Regenerates `targets/text-rungs.mjs`, the table that moves every stock rung name one step up the
// type scale. The rows are read off the pinned `ui` snapshot and the hand-written tables, so a pin
// move or a table edit is followed by a rerun instead of a hand edit.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

import { applySite } from '../component-fix.mjs';
import { BINARY_SITES } from '../targets/binary.mjs';
import { SITES } from '../targets/contrast.mjs';
import { CURSOR_SITES } from '../targets/cursor.mjs';
import { FIELD_VARIANTS } from '../targets/field-variants.mjs';
import { RADIUS } from '../targets/radius.mjs';
import { RINGS } from '../targets/rings.mjs';
import { SIZES } from '../targets/sizes.mjs';
import { SURFACES } from '../targets/surfaces.mjs';
import { shiftRungs } from '../targets/type-scale.mjs';
import { VARIANTS } from '../targets/variants.mjs';

const ROOT = fileURLToPath(new URL('../../..', import.meta.url));
const UI = join(ROOT, 'src', 'lib', 'components', 'ui');
const OUT = join(ROOT, 'packages', 'daisyui-adapter', 'targets', 'text-rungs.mjs');

// Same order as `TABLES` in targets.mjs, without importing it: the module it exports re-exports this
// file, and a cycle here would read a half-built table.
const TABLE_SITES = [
	...SITES,
	...SIZES,
	...FIELD_VARIANTS,
	...RADIUS,
	...SURFACES,
	...VARIANTS,
	...BINARY_SITES,
	...CURSOR_SITES,
	...RINGS
];

const RUNG = /text-(?:xs|sm|base|lg|xl|2xl)(?![a-z0-9-])/;
const QUOTED = /"([^"\n]*)"/g;
const PRINT_WIDTH = 100;
// Prettier counts a tab as `tabWidth` (2 by default) when it measures a line.
const lineWidth = (line) => line.replace(/\t/g, '  ').length;

const walk = (directory) =>
	readdirSync(directory, { withFileTypes: true })
		.sort((a, b) => a.name.localeCompare(b.name))
		.flatMap((entry) =>
			entry.isDirectory()
				? walk(join(directory, entry.name))
				: entry.name.endsWith('.svelte')
					? [join(directory, entry.name)]
					: []
		);

const rowsFor = (file, stock) => {
	const sites = TABLE_SITES.filter((site) => site.file === file);
	const apply = (sites, content) => sites.reduce((text, site) => applySite(text, site), content);
	const current = apply(sites, stock);
	const target = apply(
		sites.map((site) => ({ ...site, stock: shiftRungs(site.stock) })),
		shiftRungs(stock)
	);

	const rows = [];
	const seen = new Set();
	for (const [, value] of current.matchAll(QUOTED)) {
		if (!RUNG.test(value) || seen.has(value)) continue;
		const shifted = shiftRungs(value);
		if (shifted === value || current.includes(shifted) || !target.includes(shifted)) continue;
		seen.add(value);
		rows.push({ stock: value, fixed: shifted });
	}
	return rows;
};

// Prettier's `singleQuote` picks the quote that needs fewer escapes, and `trailingComma: none` plus a
// preserved first-line break keep every row expanded. Emitting that shape keeps the generated file
// clean under `prettier --check` without running prettier on it.
const quote = (text) => {
	const singles = text.split("'").length - 1;
	const doubles = text.split('"').length - 1;
	if (singles === 0) return `'${text}'`;
	if (doubles < singles) return `"${text}"`;
	return `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
};

const property = (key, value, last = false) => {
	const tail = last ? '' : ',';
	const line = `\t\t${key}: ${value}${tail}`;
	return lineWidth(line) <= PRINT_WIDTH ? [line] : [`\t\t${key}:`, `\t\t\t${value}${tail}`];
};

// One chunk per row, with the file's comment folded into its first row so the comma that separates rows
// always lands on the row itself.
const chunk = (file, row, first) => {
	const lines = [
		'\treplaceSite({',
		...property('id', quote(row.id)),
		...property('component', quote(row.component)),
		...property('file', quote(file)),
		...property('stock', quote(row.stock)),
		...property('fixed', quote(row.fixed), true),
		'\t})'
	];
	return first ? `\t// ${file}\n${lines.join('\n')}` : lines.join('\n');
};

const header = `// Generated by \`tools/generate-text-rungs.mjs\` from the pinned \`ui\` snapshot at 1.8 and the
// hand-written tables in this directory. Regenerate (\`node
// packages/daisyui-adapter/tools/generate-text-rungs.mjs\`) when the pin moves or a table's \`fixed\`
// string changes; a hand edit here is overwritten.
//
// A row shifts one class string of a stock file one rung up, so the text keeps the px it had before
// the type scale named the rungs. Every class string the tables leave alone gets a row, because the
// shift is what makes the stock match the scale rather than a list of remembered files.
import { replaceSite } from './site.mjs';

export const TEXT_RUNGS = [`;

const main = () => {
	const chunks = [];
	const counters = new Map();
	let total = 0;
	let files = 0;
	for (const path of walk(UI)) {
		const file = relative(UI, path).split(sep).join('/');
		const component = file.split('/')[0];
		const rows = rowsFor(file, readFileSync(path, 'utf8').replace(/\r\n/g, '\n')).map((row) => {
			const count = (counters.get(component) ?? 0) + 1;
			counters.set(component, count);
			return { ...row, component, id: `text-${component}-${count}` };
		});
		if (rows.length === 0) continue;
		total += rows.length;
		files += 1;
		rows.forEach((row, index) => chunks.push(chunk(file, row, index === 0)));
	}
	writeFileSync(OUT, `${header}\n${chunks.join(',\n')}\n];\n`);
	console.log(`[text-rungs] ${total} rows across ${files} files -> ${relative(ROOT, OUT)}`);
};

main();
